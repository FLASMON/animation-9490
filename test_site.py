from playwright.sync_api import sync_playwright, expect
import json

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    page = browser.new_page(viewport={'width':1440,'height':950})
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    base='http://localhost:4200'
    page.goto(base, wait_until='networkidle')
    expect(page.get_by_role('heading', level=1)).to_contain_text('Votre beauté')
    # Load lazy imagery by exercising real scroll positions.
    for y in range(0, int(page.evaluate('document.body.scrollHeight')), 650):
        page.evaluate('(y)=>window.scrollTo(0,y)',y)
        page.wait_for_timeout(80)
    page.evaluate('window.scrollTo(0,0)')
    page.screenshot(path='/home/user/botanica-final-desktop.png',full_page=True)
    assert page.locator('img').evaluate_all('(imgs)=>imgs.every(i=>i.complete && i.naturalWidth>0)')
    page.get_by_role('button',name='Rechercher',exact=True).click()
    search=page.get_by_role('textbox',name='Rechercher un soin',exact=True)
    search.press_sequentially('sérum',delay=50)
    expect(search).to_have_value('sérum')
    expect(page.locator('.search-results a')).to_have_count(1)
    page.keyboard.press('Escape')
    expect(page.locator('dialog')).to_have_count(0)
    page.goto(base+'/boutique')
    expect(page.locator('.product-card')).to_have_count(8)
    field=page.get_by_role('textbox',name='Rechercher dans le catalogue')
    field.press_sequentially('crème',delay=50)
    expect(field).to_have_value('crème')
    expect(page.locator('.product-card')).to_have_count(1)
    field.fill('')
    page.locator('.catalog-filters').get_by_role('button',name='Visage',exact=True).click()
    expect(page.locator('.product-card')).to_have_count(3)
    page.get_by_role('combobox').first.select_option('price-asc')
    expect(page.locator('.product-name').first).to_contain_text('Nettoyant')
    page.goto(base+'/produit/serum-eclat')
    page.get_by_role('button',name='Augmenter la quantité',exact=True).click()
    page.locator('.detail-buy').get_by_role('button',name='Ajouter au panier',exact=True).click()
    page.get_by_role('button',name='Ajouter ou retirer des favoris').click()
    page.reload()
    assert json.loads(page.evaluate("localStorage.getItem('botanica-cart')"))['serum-eclat']==2
    page.goto(base+'/favoris')
    expect(page.locator('.product-card')).to_have_count(1)
    page.get_by_role('button',name='Ouvrir le panier, 2 articles').click()
    expect(page.get_by_role('dialog',name='Votre panier')).to_be_visible()
    page.get_by_role('link',name='Voir mon panier').click()
    expect(page).to_have_url(base+'/panier')
    page.get_by_role('textbox',name='Code promotionnel').press_sequentially('BOTANICA10')
    page.get_by_role('button',name='Appliquer',exact=True).click()
    expect(page.locator('.summary-total')).to_contain_text('52,20')
    page.get_by_role('link',name='Passer la commande').click()
    page.get_by_role('textbox',name='Prénom',exact=True).fill('Camille')
    page.get_by_role('textbox',name='Nom',exact=True).fill('Test')
    page.get_by_role('textbox',name='Adresse e-mail pour la commande').fill('demo@example.com')
    page.get_by_role('textbox',name='Adresse',exact=True).fill('12 rue des Fleurs')
    page.get_by_role('textbox',name='Code postal').fill('75001')
    page.get_by_role('textbox',name='Ville',exact=True).fill('Paris')
    page.get_by_role('checkbox',name='Accepter la commande fictive').check()
    page.get_by_role('button',name='Confirmer la commande de démonstration').click()
    expect(page.get_by_role('heading',name='Merci pour votre visite.')).to_be_visible()
    assert json.loads(page.evaluate("localStorage.getItem('botanica-cart')"))=={}
    assert page.evaluate("localStorage.getItem('botanica-last-order')")
    page.goto(base+'/journal')
    page.locator('.article-card').first.click()
    expect(page.get_by_role('heading',level=1)).to_contain_text('Les 3 gestes')
    page.goto(base+'/contact')
    page.get_by_role('textbox',name='Votre nom',exact=True).fill('Camille Test')
    page.get_by_role('textbox',name='Votre adresse e-mail',exact=True).first.fill('demo@example.com')
    page.get_by_role('textbox',name='Votre message',exact=True).fill('Un message de démonstration pour tester le formulaire.')
    page.get_by_role('checkbox',name='Accepter l’enregistrement local du message').check()
    page.get_by_role('button',name='Enregistrer le message').click()
    expect(page.get_by_role('heading',name='Votre message est enregistré.')).to_be_visible()
    page.goto(base)
    page.locator('.newsletter-form').get_by_role('textbox').fill('demo@example.com')
    page.locator('.newsletter-form').get_by_role('checkbox').check()
    page.get_by_role('button',name='S’inscrire à la newsletter').click()
    expect(page.locator('.form-success')).to_be_visible()
    page.locator('summary').first.click()
    expect(page.locator('.faq-list details').first).to_have_attribute('open','')
    page.set_viewport_size({'width':390,'height':844})
    page.evaluate('window.scrollTo(0,0)')
    page.get_by_role('button',name='Ouvrir le menu').click()
    page.get_by_role('dialog',name='Navigation').get_by_role('link',name='Corps',exact=True).click()
    expect(page.locator('.product-card')).to_have_count(2)
    assert not page.evaluate('document.documentElement.scrollWidth>innerWidth')
    page.goto(base)
    for y in range(0,int(page.evaluate('document.body.scrollHeight')),600):
        page.evaluate('(y)=>window.scrollTo(0,y)',y)
        page.wait_for_timeout(60)
    page.evaluate('window.scrollTo(0,0)')
    page.screenshot(path='/home/user/botanica-final-mobile.png',full_page=True)
    assert not page.evaluate('document.documentElement.scrollWidth>innerWidth')
    assert not errors, errors
    print('PASS: images, search, filtering, sorting, favorites, persistent cart, promo code, checkout, journal, contact, newsletter, FAQ, mobile navigation and zero console errors.')
    browser.close()